/**
 * Generate packages/<name>/src/plugin-meta.ts from the name map (scripts/plugins.ts).
 *
 * Each plugin imports PLUGIN_NAME / PACKAGE_NAME and builds its `configs.recommended`
 * keys with presetRules(), so preset prefixes always equal the normalized plugin name
 * (the oxlint >= 1.70 rule prefix).
 *
 *   bun scripts/generate-plugin-meta.ts           # write the files
 *   bun scripts/generate-plugin-meta.ts --check   # exit 1 if any file is out of date
 */
import { join } from "node:path";
import { PLUGIN_NAMES, PLUGINS, type PluginName, packageDir } from "./plugins.ts";

export function pluginMetaSource(name: PluginName): string {
  const { packageName } = PLUGINS[name];
  return `// Generated by scripts/generate-plugin-meta.ts from scripts/plugins.ts. Do not edit.

/** Normalized plugin name: the rule prefix on oxlint >= 1.70 (\`${name}/<rule>\`). */
export const PLUGIN_NAME = ${JSON.stringify(name)};

/** npm package name, also the plugin's \`meta.name\`. */
export const PACKAGE_NAME = ${JSON.stringify(packageName)};

/** Prefix unprefixed rule names with the plugin name: { "rule": x } -> { "${name}/rule": x }. */
export function presetRules<V>(rules: Readonly<Record<string, V>>): Record<string, V> {
  const out: Record<string, V> = {};
  for (const [rule, value] of Object.entries(rules)) out[\`\${PLUGIN_NAME}/\${rule}\`] = value;
  return out;
}
`;
}

export function pluginMetaPath(name: PluginName): string {
  return join(packageDir(name), "src", "plugin-meta.ts");
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const name of PLUGIN_NAMES) {
    const path = pluginMetaPath(name);
    const want = pluginMetaSource(name);
    const file = Bun.file(path);
    const have = (await file.exists()) ? await file.text() : "";
    if (have === want) continue;
    if (check) {
      console.error(`${path} is out of date; run bun scripts/generate-plugin-meta.ts`);
      stale++;
    } else {
      await Bun.write(path, want);
      console.log(`wrote ${path}`);
    }
  }
  process.exit(stale > 0 ? 1 : 0);
}
